/// <summary>
/// The first blog articles, one per topic, created and published once on startup (every
/// environment). The admin content editor owns them after that: edits, photos and unpublishing
/// happen there, and survive deploys. Skipped when the blog has any article,
/// so deleting these doesn't bring them back (only a blog with no articles at all is seeded again). Georgian only for now; the page falls back to
/// Georgian in English. The cover photos are the site's own, in /media; replace them in the editor.
/// The texts are the second edition (Beka's Word file of 2026-11-24): they speak to the couple
/// („თქვენ"), and only the buttons keep the site's „შენ". The budget table carries the same shares
/// as the budget tool (core/budget.ts, BudgetController.DefaultItems): change them together.
/// </summary>
public static class BlogArticlesSeeder
{
    /// <summary>
    /// The current texts, for the migration that puts a new edition of these six articles over the
    /// first one in a database that already has them (the seeding below only fills an empty blog).
    /// </summary>
    internal static IEnumerable<(string Slug, string Title, string Excerpt, string Meta, string ActionLabel, string Body)> Texts =>
        Drafts.Select(d => (d.Slug, d.Title, d.Excerpt, d.Meta, d.ActionLabel, d.Body.Trim().ReplaceLineEndings("\n")));

    private sealed record Draft(
        string Slug, string Topic, string Title, string Excerpt, string Meta,
        string Cover, string CoverAlt, string ActionPath, string ActionLabel, string Body);

    public static async Task SeedAsync(AppDbContext db)
    {
        // Any article at all means the blog has been started. Looking only for these slugs
        // brought all six back on the next restart once the admin had deleted the last of them.
        if (await db.ContentPages.AnyAsync(c => c.Type == ContentPageType.Article))
            return;

        var now = DateTimeOffset.UtcNow;
        // The list is newest first: a minute apart, so "where to start" comes first.
        var order = 0;
        foreach (var d in Drafts)
        {
            var publishedAt = now.AddMinutes(-order++);
            db.ContentPages.Add(new ContentPage
            {
                Type = ContentPageType.Article,
                Slug = d.Slug,
                Topic = d.Topic,
                TitleKa = d.Title,
                ExcerptKa = d.Excerpt,
                MetaDescriptionKa = d.Meta,
                BodyKa = d.Body.Trim(),
                ActionPath = d.ActionPath,
                ActionLabelKa = d.ActionLabel,
                IsPublished = true,
                PublishedAt = publishedAt,
                CreatedAt = now,
                UpdatedAt = now,
                Photos = new List<ContentPhoto> { new() { Url = d.Cover, AltKa = d.CoverAlt, SortOrder = 0 } },
            });
        }

        await db.SaveChangesAsync();
    }

